#!/usr/bin/env python3
"""
Generate name<->number enums from a title's syscall + string tables, so tools and
readers use natural-language names instead of numbers.

    py -3 tools/gen_enums.py <title_dir>      # e.g. ../rot3k2-snes-decompiler
Reads:
  <title_dir>/data/syscall_names.toml   ([[syscall]] id + name)
  <title_dir>/data/strings.toml         ([table.NAME] base + labels[])  -> index enums
Emits <title_dir>/data/enums.py with:
  SYSCALLS = {id: name}, SYSCALL_ID = {name: id}
  STRING_TABLES = {table: {index: label}}, STRING_TABLE_BASE = {table: base_addr}
The bytecode tools import these to render `call.p sys_blit_rect` and a table index
as `diplomacy_prompt[5] = ally_whom`. Strings self-ground; treated like enums.
"""
import os, re, sys


def parse_syscalls(path):
    out, cur = {}, None
    if not os.path.exists(path):
        return out
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        m = re.match(r"id\s*=\s*(0x[0-9A-Fa-f]+|\d+)", line)
        if m:
            cur = int(m.group(1), 0); continue
        m = re.match(r'name\s*=\s*"([^"]+)"', line)
        if m and cur is not None:
            out[cur] = m.group(1); cur = None
    return out


def parse_string_tables(path):
    """{table_name: (base_addr, [labels])} from [table.NAME] blocks."""
    tables = {}
    if not os.path.exists(path):
        return tables
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r"\[table\.(\w+)\](.*?)(?=\n\[|\Z)", text, re.S):
        name, body = m.group(1), m.group(2)
        bm = re.search(r"base\s*=\s*(0x[0-9A-Fa-f]+|\d+)", body)
        lm = re.search(r"labels\s*=\s*\[(.*?)\]", body, re.S)
        base = int(bm.group(1), 0) if bm else 0
        labels = re.findall(r'"([^"]*)"', lm.group(1)) if lm else []
        tables[name] = (base, labels)
    return tables


def main(argv):
    # argv[1] = a MODULE data dir (e.g. .../data/root). syscall_names.toml is shared:
    # look in the module dir, else the parent data/ (native syscalls are title-global).
    d = argv[1] if len(argv) > 1 else "."
    sc_here = os.path.join(d, "syscall_names.toml")
    sc_path = sc_here if os.path.exists(sc_here) else os.path.join(os.path.dirname(d), "syscall_names.toml")
    sc = parse_syscalls(sc_path)
    tab = parse_string_tables(os.path.join(d, "strings.toml"))
    dst = os.path.join(d, "enums.py")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("# AUTO-GENERATED by koei-snes/tools/gen_enums.py -- do not edit by hand.\n")
        f.write("# Read syscalls + string-table indexes by name, not number.\n\n")
        f.write("SYSCALLS = {\n")
        for i in sorted(sc):
            f.write("    0x%02X: %r,\n" % (i, sc[i]))
        f.write("}\nSYSCALL_ID = {v: k for k, v in SYSCALLS.items()}\n\n")
        f.write("STRING_TABLE_BASE = {\n")
        for name, (base, _l) in sorted(tab.items()):
            f.write("    %r: 0x%04X,\n" % (name, base))
        f.write("}\n\nSTRING_TABLES = {\n")
        for name, (_b, labels) in sorted(tab.items()):
            f.write("    %r: {%s},\n" % (name, ", ".join("%d: %r" % (i, l) for i, l in enumerate(labels))))
        f.write("}\n")
    print("wrote %s: %d syscalls, %d string tables (%s)" %
          (dst, len(sc), len(tab), ", ".join("%s[%d]" % (n, len(l)) for n, (_b, l) in tab.items())))


if __name__ == "__main__":
    main(sys.argv)
