"""Python side of the Mesen 2 bridge: launch Mesen with bridge.lua and drive it in lockstep.

Machine-agnostic. A machine layer (e.g. emu_harness.machines.nes) supplies the button names, the
memory type to read and any battery-save handling.
"""
from __future__ import annotations

import os
import socket
import subprocess
import time
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
BRIDGE_LUA = Path(__file__).resolve().parent / "bridge.lua"


def load_config(path: Path | None = None) -> dict:
    path = path or REPO / "config.toml"
    if not path.exists():
        raise FileNotFoundError(f"{path} missing: copy config.example.toml and set this machine's paths")
    cfg = tomllib.loads(path.read_text(encoding="utf-8"))
    cfg["mesen"] = Path(cfg["mesen"])
    cfg["home"] = Path(cfg.get("home") or cfg["mesen"].parent)
    return cfg


def save_files(home: Path, rom: Path) -> list[Path]:
    """Battery/save-RAM files Mesen keeps for this ROM (named after the ROM file)."""
    return [p for p in (home / "Saves").glob(glob_escape(rom.stem) + ".*")]


def debugger_dir(config: dict | None = None) -> Path:
    """Where Mesen's GUI debugger writes memory dumps (*.dmp) and trace logs (*.txt)."""
    return (config or load_config())["home"] / "Debugger"


def debugger_files(suffix: str, name: str | None = None, config: dict | None = None) -> list[Path]:
    """Files of one type in the Debugger folder, newest first; `name` keeps those whose file name
    contains it (case-insensitive)."""
    d = debugger_dir(config)
    fs = [p for p in d.iterdir() if p.is_file() and p.suffix.lower() == suffix.lower()] if d.is_dir() else []
    if name:
        fs = [p for p in fs if name.lower() in p.name.lower()]
    return sorted(fs, key=lambda p: p.stat().st_mtime, reverse=True)


def glob_escape(s: str) -> str:
    return "".join(f"[{c}]" if c in "[]*?" else c for c in s)


class BridgeError(RuntimeError):
    pass


class Mesen:
    """One Mesen instance, driven frame by frame through bridge.lua.

    headless=True uses --testRunner: the script is attached before the first frame,
    so frame 0 is power-on. GUI mode attaches the script after the ROM has started.
    """

    def __init__(self, rom: Path, *, keys: list[str], port: int = 0, headless: bool = True,
                 run_timeout_s: int = 86400, config: dict | None = None, log_dir: Path | None = None,
                 switches: list[str] = (), scripts: list[Path] = ()):
        """scripts: a title's own Lua probes, run unchanged beside the bridge; their emu.log output
        goes to `self.script_log` (a file) instead of Mesen's script window."""
        cfg = config or load_config()
        self.rom = Path(rom)
        self.keys = list(keys)
        self.inputs: list[int] = []          # one mask per emulated frame since power-on
        self.input_log_valid = True          # False once a savestate load breaks the frame chain
        srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        srv.bind(("127.0.0.1", 0))
        srv.listen(1)
        env = dict(os.environ, MESEN_HARNESS_PORT=str(srv.getsockname()[1]))
        args = [str(cfg["mesen"])]
        if headless:
            args += ["--testRunner", f"--timeout={run_timeout_s}"]
        # Mesen config overrides, e.g. "--Nes.RamPowerOnState=AllOnes". Only bool/enum settings
        # and numbers with a [MinMax] range apply; others are silently ignored (ConfigManager.cs).
        args += list(switches)
        log_dir = log_dir or REPO / "_scratch"
        log_dir.mkdir(exist_ok=True)
        self.script_log = None
        lua = BRIDGE_LUA
        if scripts:
            stamp = time.time_ns()
            self.script_log = log_dir / f"scripts_{stamp}.log"
            lua = log_dir / f"harness_{stamp}.lua"
            lua.write_text("\n".join([
                "-- generated by emu-harness: title probes (emu.log -> a file), then the bridge",
                f"local logf = assert(io.open([[{self.script_log}]], 'w'))",
                "emu.log = function(s) logf:write(tostring(s), '\\n'); logf:flush() end",
                *(f"dofile([[{Path(p).resolve()}]])" for p in scripts),
                f"dofile([[{BRIDGE_LUA}]])", ""]))
        args += [str(lua), str(self.rom)]
        self._log = open(log_dir / f"mesen_{int(time.time())}.log", "w")
        self.proc = subprocess.Popen(args, env=env, stdout=self._log, stderr=subprocess.STDOUT)
        srv.settimeout(30)
        try:
            self.conn, _ = srv.accept()
        except socket.timeout:
            self.proc.kill()
            raise BridgeError("Mesen never connected to the bridge (Lua network access enabled?)")
        finally:
            srv.close()
        self.conn.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        self.conn.settimeout(600)
        self._rf = self.conn.makefile("rb")
        if self.cmd("ping") != "pong":
            raise BridgeError("bad handshake")
        self.cmd("keys " + ",".join(self.keys))

    # -- wire ---------------------------------------------------------------
    def cmd(self, line: str) -> str:
        self.conn.sendall((line + "\n").encode())
        resp = self._rf.readline()
        if not resp:
            code = self.proc.poll()
            raise BridgeError(f"bridge connection lost; Mesen exit code {code}")
        resp = resp.decode().rstrip("\n")
        if resp.startswith("err "):
            raise BridgeError(resp)
        return resp

    @staticmethod
    def _frame(resp: str) -> int:
        k, _, v = resp.partition("=")
        if k != "frame":
            raise BridgeError(f"expected frame=, got {resp!r}")
        return int(v)

    # -- input (every frame goes through here: the one recorder) -------------
    def mask(self, buttons) -> int:
        m = 0
        for b in buttons:
            m |= 1 << self.keys.index(b)
        return m

    def step(self, buttons=(), frames: int = 1, port: int = 0) -> int:
        m = self.mask(buttons)
        self.inputs.extend([m] * frames)
        return self._frame(self.cmd(f"step {frames} {m} {port}"))

    def run_masks(self, masks: list[int], port: int = 0, chunk: int = 4096) -> int:
        """Apply one mask per frame. Returns the frame counter after the last one."""
        if len(self.keys) > 8:
            raise ValueError("seq packs one byte per frame; more than 8 buttons needs a wider encoding")
        f = None
        for i in range(0, len(masks), chunk):
            part = masks[i:i + chunk]
            self.inputs.extend(part)
            f = self._frame(self.cmd(f"seq {port} " + "".join(f"{m:02x}" for m in part)))
        return f if f is not None else self.frame()

    # -- state --------------------------------------------------------------
    def info(self) -> dict:
        return dict(kv.split("=", 1) for kv in self.cmd("info").split(" ", 2))

    def frame(self) -> int:
        return int(self.info()["frame"])

    def read(self, mem_type: str, addr: int, length: int = 1) -> bytes:
        return bytes.fromhex(self.cmd(f"read {mem_type} {addr} {length}"))

    def save(self) -> str:
        return self.cmd("save")

    def load(self, state: str) -> int:
        self.input_log_valid = False
        return self._frame(self.cmd(f"load {state}"))

    def trace(self, mem_type: str, addr: int, length: int, path: Path,
              flag_addr: int | None = None) -> None:
        """Append, at every endFrame from now on, 1 flag byte (flag_addr read during the frame)
        + `length` bytes from `addr` to `path`. trace_off() closes it."""
        spec = f"{mem_type} {addr} {length} {Path(path)}"
        if flag_addr is not None:
            spec += f"|{flag_addr}"
        self.cmd("trace " + spec)

    def trace_off(self) -> None:
        self.cmd("trace off")

    def cdl(self, mem_type: str, path: Path) -> bytes:
        """Mesen's code/data log for `mem_type` (e.g. nesPrgRom): one flag byte per byte of that
        memory, accumulated since power-on. Written to `path` by the emulator, returned here."""
        resp = self.cmd(f"cdl {mem_type} {Path(path)}")
        data = Path(path).read_bytes()
        if not resp.startswith("ok ") or int(resp.split()[1]) != len(data):
            raise BridgeError(f"cdl: {resp!r}, file has {len(data)} bytes")
        return data

    def write(self, mem_type: str, addr: int, data: bytes) -> None:
        resp = self.cmd(f"write {mem_type} {addr} {bytes(data).hex()}")
        if resp != f"ok {len(data)}":
            raise BridgeError(f"write: {resp!r}")

    def screenshot(self, path: Path) -> Path:
        """The console's own rendered frame as a PNG (Mesen's takeScreenshot). Never the desktop."""
        resp = self.cmd(f"shot {Path(path)}")
        if not resp.startswith("ok ") or int(resp.split()[1]) != Path(path).stat().st_size:
            raise BridgeError(f"shot: {resp!r}")
        return Path(path)

    def state(self, prefix: str = "") -> dict[str, str]:
        """emu.getState() scalars (key names are Mesen's, per console), e.g. state("cpu.")."""
        line = self.cmd(f"state {prefix}".rstrip())
        return dict(kv.split("=", 1) for kv in line.split()) if line else {}

    def watch(self, kind: str, start: int, end: int, path: Path, *, regs: bool = False,
              ranges=()) -> int:
        """Log every exec/read/write hit in [start, end] to `path`, one text line per hit:
        frame address value [cpu.* registers] [hex per range]; ranges = (memType, addr, len), where
        addr "*N" reads at the address held in the word at N (a VM's PC, a pointer).
        Returns the watch id for watch_off. Parse the file with read_watch."""
        spec = f"{kind} {start} {end} {Path(path)}" + (" regs" if regs else "")
        spec += "".join(f" {mt}:{a}:{n}" for mt, a, n in ranges)   # a = int, or "*ptr" (indirect)
        resp = self.cmd("watch " + spec)
        if not resp.startswith("ok "):
            raise BridgeError(f"watch: {resp!r}")
        return int(resp.split()[1])

    def watch_off(self, wid: int | None = None) -> None:
        self.cmd("watch off" + (f" {wid}" if wid is not None else ""))

    def input_keys(self, port: int = 0) -> list[str]:
        return self.cmd(f"inputkeys {port}").split(",")

    # -- lifecycle ------------------------------------------------------------
    def close(self) -> int | None:
        try:
            self.cmd("quit")
        except Exception:
            pass
        try:
            self.conn.close()
        except Exception:
            pass
        try:
            code = self.proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.proc.kill()
            code = None
        self._log.close()
        return code

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()


def read_watch(path: Path) -> list[dict]:
    """A watch log -> one dict per hit, keyed by the header's column names. frame/address/value
    and cpu.* come back as ints where they parse; ranges stay as bytes."""
    lines = Path(path).read_text().splitlines()
    if not lines or not lines[0].startswith("# "):
        raise ValueError(f"{path}: not a watch log")
    cols = lines[0][2:].split()
    out = []
    for line in lines[1:]:
        row = {}
        for k, v in zip(cols, line.split()):
            if ":" in k:
                row[k] = bytes.fromhex(v)
            else:
                try:
                    row[k] = int(v)
                except ValueError:
                    row[k] = v
        out.append(row)
    return out


def read_trace(path: Path, length: int) -> list[tuple[int, bytes]]:
    """A `trace` file -> one (flag, bytes) per frame: flag is 1 when the trace's flag address was
    read during that frame (0 without one), bytes are the `length` traced bytes."""
    data = Path(path).read_bytes()
    n = 1 + length
    return [(data[i], data[i + 1:i + n]) for i in range(0, len(data) - n + 1, n)]
